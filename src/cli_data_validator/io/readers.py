"""Data Reader module.

Provides streaming readers for ingesting dataset files line-by-line.
"""

import csv
from collections.abc import Generator
from pathlib import Path

class CSVReader:
    """Reader class for streaming records from CSV files."""

    @staticmethod
    def read(file_path: Path) -> Generator[dict[str, str], None, None]:
        """Reads a CSV file and yields each row as a dictionary.

        Args:
            file_path: Path object pointing to the CSV dataset file.

        Yields:
            dict[str, str]: A dictionary mapping column headers to row cell values.

        Raises:
            FileNotFoundError: If the specified CSV file does not exist.
        """
        # Uses 'utf-8-sig' encoding to automatically handle and strip potential
        # Byte Order Marks (BOM) from files generated by Windows or Excel.
        with open(file_path, mode="r", encoding="utf-8-sig") as file:
            reader = csv.DictReader(file)
            for line in reader:
                yield line
